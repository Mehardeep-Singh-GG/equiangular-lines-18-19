def a_m_coset(m: int, k: int) -> Tuple[int, List[np.ndarray]]:
    """Return (embedding_dim, list of minimal norm vectors in k * alpha_m + A_m).
    Wait: use integer coords multiplied by (m+1) so everything is exact integers!
    In Z^{m+1}, (m+1)*alpha_m^{(I)} has (m+1 - k) on I^c and -(k) on I?
    Wait: alpha_m = 1/(m+1) * 1 - e_i, sum_{i in I} alpha_m^{(i)} = k/(m+1)*1 - e_I.
    Multiply by (m+1): k on I^c, and (k - (m+1)) = -(m+1-k) on I.
    Squared norm of unscaled vector is k*(m+1-k)/(m+1).
    """
    k = k % (m + 1)
    if k == 0:
        return m + 1, [np.zeros(m + 1, dtype=np.int64)]
    vecs = []
    for comb in itertools.combinations(range(m + 1), k):
        v = np.full(m + 1, k, dtype=np.int64)
        for idx in comb:
            v[idx] = k - (m + 1)
        vecs.append(v)
    return m + 1, vecs


def d_m_coset(m: int, kind: str) -> Tuple[int, List[np.ndarray]]:
    """Return (m, list of minimal norm vectors in coset `kind` of D_m^*/D_m), scaled by 2."""
    if kind == "0":
        return m, [np.zeros(m, dtype=np.int64)]
    elif kind == "v":  # vector coset: +-2 e_i (norm 1 -> scaled by 2 gives norm^2 = 4)
        vecs = []
        for i in range(m):
            for s in (2, -2):
                v = np.zeros(m, dtype=np.int64)
                v[i] = s
                vecs.append(v)
        return m, vecs
    elif kind in ("s", "c"):  # spinor coset: (+-1)^m with even/odd minus signs (norm m/4 -> scaled by 2 gives m)
        target_parity = 0 if kind == "s" else 1
        vecs = []
        for signs in itertools.product([-1, 1], repeat=m):
            neg = sum(1 for s in signs if s == -1)
            if neg % 2 == target_parity:
                vecs.append(np.array(signs, dtype=np.int64))
        return m, vecs
    raise ValueError(kind)


def max_clique_fast(adj: np.ndarray, time_limit: float = 5.0) -> List[int]:
    """Greedy + randomized local search + exact B&B (if small) for max clique on boolean adj."""
    n = adj.shape[0]
    if n == 0:
        return []
    degs = adj.sum(axis=1)
    # Multi-start greedy + 1-opt/2-opt swap local search
    rng = np.random.default_rng(42)
    best: List[int] = []
    t0 = time.time()

    # Exact B&B if n <= 200
    if n <= 200:
        adj_sets = [set(np.where(adj[i])[0]) for i in range(n)]
        order = np.argsort(-degs)
        def bk(R, P):
            nonlocal best
            if time.time() - t0 > time_limit:
                return
            if len(R) + len(P) <= len(best):
                return
            if not P:
                if len(R) > len(best):
                    best = list(R)
                return
            u = max(P, key=lambda v: len(adj_sets[v] & P))
            cands = sorted(P - adj_sets[u], key=lambda v: -len(adj_sets[v] & P))
            P_cur = set(P)
            for v in cands:
                if time.time() - t0 > time_limit:
                    return
                if len(R) + len(P_cur) <= len(best):
                    return
                bk(R + [v], P_cur & adj_sets[v])
                P_cur.remove(v)
        bk([], set(range(n)))
        return best

    # Randomized greedy + plateau swap for larger n
    adj_sets = [set(np.where(adj[i])[0]) for i in range(n)]
    for trial in range(400):
        if time.time() - t0 > time_limit:
            break
        start = int(rng.integers(0, n)) if trial > 0 else int(np.argmax(degs))
        clq = [start]
        cands = adj_sets[start].copy()
        while cands:
            # Pick top-degree candidate in cands (with slight randomness)
            if trial == 0:
                nxt = max(cands, key=lambda v: len(adj_sets[v] & cands))
            else:
                clist = list(cands)
                scores = [len(adj_sets[v] & cands) for v in clist]
                mx = max(scores)
                top = [clist[i] for i, s in enumerate(scores) if s >= mx - 1]
                nxt = int(top[int(rng.integers(0, len(top)))])
            clq.append(nxt)
            cands &= adj_sets[nxt]
        # 1-swap / 2-add plateau expansion: delete 1 vertex, see if >=2 can be added
        improved = True
        while improved and time.time() - t0 < time_limit:
            improved = False
            clq_set = set(clq)
            for idx_drop in range(len(clq)):
                sub = clq_set - {clq[idx_drop]}
                # Common neighbors of sub
                common = set(range(n)) - sub
                for u in sub:
                    common &= adj_sets[u]
                if len(common) >= 2:
                    # Find clique >= 2 in common
                    com_list = list(common)
                    for i in range(len(com_list)):
                        u = com_list[i]
                        if u == clq[idx_drop]:
                            continue
                        for j in range(i + 1, len(com_list)):
                            v = com_list[j]
                            if v in adj_sets[u]:
                                clq = sorted(sub | {u, v})
                                improved = True
                                break
                        if improved:
                            break
                if improved:
                    break
        if len(clq) > len(best):
            best = list(clq)
    return best


def search_overlattice_from_blocks(
    name: str,
    d: int,
    block_specs: List[Tuple[str, int]],
    glue_generators: List[Tuple[int, ...]],
) -> Tuple[int, int]:
    """Given blocks (e.g., [('A', 7), ('A', 7), ('A', 3), ('A', 1), ('A', 1)])
    where the LAST block is the switching A_1, and glue generators in the dual quotient
    (each tuple specifies coset index per block), generate the integral overlattice
    cosets containing vectors of norm 3 with <x, r> = 1, build compatibility graph,
    and search for maximum cliques!
    """
    # Compute scale factors and orders per block
    orders = []
    scales = []
    for typ, m in block_specs:
        if typ == "A":
            orders.append(m + 1)
            scales.append(m + 1)
        elif typ == "D":
            orders.append(4)  # we represent Z_2 x Z_2 or Z_4 via 0,1,2,3 -> 0,v,s,c
            scales.append(2)
        else:
            raise ValueError(typ)

    # LCM of scales to embed entire lattice into integer Z^M
    L_scale = 1
    for s in scales:
        L_scale = int(np.lcm(L_scale, s))

    # Generate all coset tuples in the subgroup generated by glue_generators
    # For A_m: coset addition is mod (m+1).
    # For D_m: 0=(0,0), v=(1,1) [Wait: for even m, s+s=0, c+c=0, s+c=v; for odd m, s+s=v, s+c=0].
    def add_coset(b_idx, c1, c2):
        typ, m = block_specs[b_idx]
        if typ == "A":
            return (c1 + c2) % (m + 1)
        else:  # D_m
            # Use encoding: 0='0', 1='v', 2='s', 3='c'
            if m % 2 == 0:
                table = {
                    (0,0):0, (0,1):1, (0,2):2, (0,3):3,
                    (1,0):1, (1,1):0, (1,2):3, (1,3):2,
                    (2,0):2, (2,1):3, (2,2):0, (2,3):1,
                    (3,0):3, (3,1):2, (3,2):1, (3,3):0,
                }
            else:
                table = {
                    (0,0):0, (0,1):1, (0,2):2, (0,3):3,
                    (1,0):1, (1,1):0, (1,2):3, (1,3):2,
                    (2,0):2, (2,1):3, (2,2):1, (2,3):0,
                    (3,0):3, (3,1):2, (3,2):0, (3,3):1,
                }
            return table[(c1, c2)]

    # BFS coset group
    zero = tuple(0 for _ in block_specs)
    cosets = {zero}
    queue = [zero]
    while queue:
        cur = queue.pop()
        for g in glue_generators:
            nxt = tuple(add_coset(i, cur[i], g[i]) for i in range(len(block_specs)))
            if nxt not in cosets:
                cosets.add(nxt)
                queue.append(nxt)

    # Filter cosets whose switching-A_1 component is 1 (so <x, r> = 1)
    # AND whose sum of minimal norms is <= 3 (in fact == 3 or == 3 - 2*k? Wait: minimal norms!)
    def min_norm_num_den(b_idx, c) -> Tuple[int, int]:
        typ, m = block_specs[b_idx]
        if typ == "A":
            k = c % (m + 1)
            return k * (m + 1 - k), m + 1
        else:
            if c == 0: return 0, 1
            if c == 1: return 1, 1
            return m, 4

    # Check integrality of all cosets! (Minimum norm of nonzero coset? Better: check actual vectors!)
    # For each coset with last entry == 1 and min_norm == 3 (or 2 + 1? Wait: if min_norm == 1, adding a root gives norm 3! Let's check min_norm == 3 first, and min_norm == 1 too!)
    from fractions import Fraction
    cand_cosets = []
    for c in sorted(cosets):
        if c[-1] != 1:
            continue
        tot = sum(Fraction(*min_norm_num_den(i, c[i])) for i in range(len(block_specs)))
        if tot == 3:
            cand_cosets.append(c)

    # Build explicit integer vectors (scaled by L_scale) for all cand_cosets
    # Note: we only keep one representative of {x, r - x} (canonicalize cosets up to c -> -c!)
    def neg_coset(b_idx, c):
        typ, m = block_specs[b_idx]
        if typ == "A":
            return (-c) % (m + 1)
        else:
            if m % 2 == 0 or c in (0, 1):
                return c
            return 3 if c == 2 else 2

    # Build vector lists per block-coset
    block_vecs_cache: Dict[Tuple[int, int], np.ndarray] = {}
    for c in cand_cosets:
        for i, ci in enumerate(c[:-1]):  # omit last A_1 (fixed to alpha_1!)
            key = (i, ci)
            if key not in block_vecs_cache:
                typ, m = block_specs[i]
                if typ == "A":
                    _, vs = a_m_coset(m, ci)
                else:
                    kind = ["0", "v", "s", "c"][ci]
                    _, vs = d_m_coset(m, kind)
                mult = L_scale // scales[i]
                block_vecs_cache[key] = np.array(vs, dtype=np.int64) * mult

    # Combine vectors per coset; drop switching-A_1 coord since all have alpha_1,
    # Wait: in r^perp, 2*x - r has 0 in the last A_1 slot!
    # Check: 2*alpha_1 - 2*alpha_1 = 0!
    # So the projected vector v = L_scale * (2*x - r) has ONLY the first (len-1) blocks,
    # multiplied by 2! Wait: let's just keep x's first (len-1) blocks scaled by L_scale,
    # and remember <x, x'> = <x_rest, x'_rest> + 1/2!
    # Wait: <x, x'> in {0, 1}  <=>  <x_rest, x'_rest> in {-1/2, +1/2}  <=>  scaled ip in {-L^2/2, +L^2/2}!
    all_vecs = []
    seen_pairs = set()
    for c in cand_cosets:
        # Check if neg(c) already seen (note neg_coset on last A_1 is 1 -> 1!)
        c_neg = tuple(neg_coset(i, c[i]) for i in range(len(block_specs)))
        if c_neg < c:
            continue
        lists = [block_vecs_cache[(i, c[i])] for i in range(len(block_specs) - 1)]
        # Cartesian product
        prod_sz = 1
        for lst in lists:
            prod_sz *= len(lst)
        if prod_sz > 5000:
            continue
        for combo in itertools.product(*lists):
            vec = np.concatenate(combo)
            if c == c_neg:
                # Self-conjugate coset: deduplicate x vs -x!
                neg_t = tuple((-vec).tolist())
                t = tuple(vec.tolist())
                if neg_t in seen_pairs:
                    continue
                seen_pairs.add(t)
            all_vecs.append(vec)

    if not all_vecs:
        return 0, 0
    V = np.vstack(all_vecs)
    # Check norms^2 == (5/2) * L_scale^2
    target_norm_rest = (5 * L_scale * L_scale) // 2
    norms = np.sum(V * V, axis=1)
    assert np.all(norms == target_norm_rest), f"Norm mismatch: {set(norms)} vs {target_norm_rest}"

    # Verify integrality of inner products: <x_rest, x'_rest> + 1/2 in Z
    G_rest = V @ V.T
    half_L2 = (L_scale * L_scale) // 2
    # Check if all G_rest + half_L2 are multiples of L_scale^2 (integrality check!)
    L2 = L_scale * L_scale
    if not np.all(((G_rest + half_L2) % L2) == 0):
        print(f"  [WARN] {name}: not an integral lattice!")
        return len(V), 0

    # Compatibility: <x, x'> in {0, 1} <=> G_rest in {-half_L2, +half_L2}
    adj = (G_rest == half_L2) | (G_rest == -half_L2)
    np.fill_diagonal(adj, False)

    clq = max_clique_fast(adj, time_limit=6.0)
    k = len(clq)
    print(f"  [{name}] d={d} |X/sw|={len(V)} max_clique={k}")

    # If k >= 58 (for d=18) or k >= 73 (for d=19), or even k >= 57 / 72, verify in SymPy!
    if (d == 18 and k >= 57) or (d == 19 and k >= 72):
        # Embed 2*x_rest (norm^2 = 10 * L_scale^2, ip = +-2 * L_scale^2)
        vecs_2x = (2 * V[clq]).tolist()
        S, info = verify_vectors_gram(
            vecs_2x,
            norm_sq=10 * L_scale * L_scale,
            allowed_ips=(-2 * L_scale * L_scale, 2 * L_scale * L_scale),
            d=d,
            compute_charpoly=(k >= 58 or k >= 73),
        )
        print(f"    -> VERIFIED! n={k}, rank={info['rank']}, PSD={info['psd_verified']}")
        if (d == 18 and k >= 58) or (d == 19 and k >= 73):
            save_verified_matrix(RESULTS_DIR / f"DISCOVERY_{d}_{k}_{name}.json", f"DISCOVERY_{name}", S, info)
    return len(V), k


