"""Systematic Root-Overlattice Search for equiangular lines (alpha = 1/5) in R^18 and R^19.

Constructs integral overlattices Lambda of rank-(d+1) root lattices L = R (+) A_1
where A_1 is generated by the switching root r (||r||^2 = 2), enumerates all
norm-3 vectors X = {x in Lambda : ||x||^2 = 3, <x, r> = 1}, builds the
switching-pair compatibility graph on X / {x ~ r-x} (edge iff <x, x'> in {0, 1}),
and searches for maximum cliques using exact branch-and-bound / greedy+local search.
"""

